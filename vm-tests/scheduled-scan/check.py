ENABLE_SCHEDULE_TOGGLE = (868, 225)
APPLY_SCHEDULE_BUTTON = (867, 143)
SCHEDULED_TAB = (526, 745)
SCANNER_TAB = (679, 745)
RUN_NOW_BUTTON = (979, 744)
SIDEBAR_COLUMN = 80
SIGNATURES_ROW = 259
HARDENING_ROW = 297
SCAN_UNIT = "clamdscan.service"
SCANNED_FILE = "/var/lib/sample-scan/dropper.bin"

machine.start()
wait_for_desktop()
wait_for_lazaret_service()
machine.succeed("systemctl start clamav-daemon.service")
machine.wait_until_succeeds("clamdscan --ping 1", timeout=timedelta(seconds=120))
machine.succeed(f"printf %s {shlex.quote(EICAR_TEXT)} > {SCANNED_FILE}")

with subtest("the Protection page shows the system timer"):
    activate_application_action("show-window")
    wait_for_lazaret_window()
    time.sleep(3)
    machine.screenshot("protection_page")

with subtest("Run Now asks for a password and runs the system scan"):
    click_at(RUN_NOW_BUTTON[0], RUN_NOW_BUTTON[1])
    time.sleep(3)
    machine.screenshot("password_prompt")
    answer_password_prompt()
    machine.wait_until_succeeds(
        f"journalctl -u {SCAN_UNIT} --no-pager --output=cat | grep -q '{SCANNED_FILE}.*FOUND'",
        timeout=timedelta(seconds=120),
    )
    machine.wait_until_succeeds(f"systemctl show -p Result --value {SCAN_UNIT} | grep -q exit-code", timeout=timedelta(seconds=60))
    exit_status = machine.succeed(f"systemctl show -p ExecMainStatus --value {SCAN_UNIT}").strip()
    assert exit_status == "1", f"a detection should exit 1: {exit_status}"

with subtest("finding malware is not shown as a scanner failure"):
    machine.screenshot("scan_finished_toast")
    machine.wait_for_text("found malware", timeout=timedelta(seconds=30))
    screen = machine.get_screen_text()
    assert "did not finish cleanly" not in screen, screen

with subtest("the scan's journal line becomes a detection that is not called blocked"):
    wait_for_stored_detection(SCANNED_FILE)
    detection = stored_detection(SCANNED_FILE).split("|")
    assert detection[0].startswith("Win.Fixture.Agent-1"), detection
    assert detection[1] == "0" and detection[2] == "1", f"wrong source: {detection}"
    matching = wait_for_notification("Malware found")
    assert not notifications_mentioning("Malware blocked"), matching
    time.sleep(2)
    machine.screenshot("protection_after_scan")
    assert "ended with an error" not in machine.get_screen_text(), "a found threat was shown as a failed scan"

with subtest("the Lazaret schedule is locked because the system has a timer"):
    activate_application_action("preferences")
    time.sleep(3)
    click_at(SCHEDULED_TAB[0], SCHEDULED_TAB[1])
    time.sleep(2)
    machine.screenshot("preferences_scheduled")
    click_at(ENABLE_SCHEDULE_TOGGLE[0], ENABLE_SCHEDULE_TOGGLE[1])
    click_at(APPLY_SCHEDULE_BUTTON[0], APPLY_SCHEDULE_BUTTON[1])
    time.sleep(2)
    as_user(f"test ! -e /home/{SAMPLE_USER}/.config/systemd/user/lazaret-scheduled-scan.timer")

with subtest("settings the system owns are locked and copy a snippet"):
    click_at(SCANNER_TAB[0], SCANNER_TAB[1])
    time.sleep(2)
    machine.screenshot("preferences_scanner")
    machine.wait_for_text("generated by", timeout=timedelta(seconds=30))

with subtest("signature sources and hardening have their own pages"):
    machine.send_key("esc")
    time.sleep(1)
    click_at(SIDEBAR_COLUMN, SIGNATURES_ROW)
    time.sleep(2)
    machine.screenshot("signatures_page")
    machine.wait_for_text("Signature Sources", timeout=timedelta(seconds=60))
    click_at(SIDEBAR_COLUMN, HARDENING_ROW)
    time.sleep(2)
    machine.screenshot("hardening_page")
    machine.wait_for_text("Firewall", timeout=timedelta(seconds=60))
